"""
report.py
Markdown and JSON report generator for AgentWall-Supply.
"""

from .scorer import ServerReport

_TIER_EMOJI = {"CRITICAL": "🔴", "HIGH": "🟠", "MEDIUM": "🟡", "LOW": "🟢"}


def report_to_dict(report: ServerReport) -> dict:
    return {
        "server_name": report.server_name,
        "score": report.score,
        "tier": report.tier,
        "drift": {
            "is_new_server": report.drift.is_new_server,
            "added_tools": report.drift.added_tools,
            "removed_tools": report.drift.removed_tools,
            "changed_tools": report.drift.changed_tools,
        },
        "tools": [
            {
                "name": tr.tool.name,
                "score": tr.score,
                "tier": tr.tier,
                "injection_findings": [
                    {"label": f.pattern_label, "severity": f.severity, "snippet": f.matched_snippet}
                    for f in tr.semantic.injection_findings
                ],
                "permission_categories": sorted(tr.permissions.categories),
                "name_desc_similarity": round(tr.semantic.name_desc_similarity, 3),
                "mismatch_flag": tr.semantic.mismatch_flag,
                "drift_flag": tr.drift_flag,
                "sandbox_violations": [
                    {"type": v.violation_type, "severity": v.severity, "details": v.details}
                    for v in (tr.sandbox_result.violations if tr.sandbox_result else [])
                ],
            }
            for tr in report.tool_reports
        ],
    }


def render_markdown(report: ServerReport) -> str:
    lines = []
    lines.append(f"# AgentWall-Supply Security Audit — `{report.server_name}`")
    lines.append("")
    lines.append(f"**Server risk score: {report.score}/100** "
                 f"{_TIER_EMOJI[report.tier]} **{report.tier}**")
    lines.append("")

    if report.drift.is_new_server:
        lines.append("_First scan of this server — baseline recorded._")
    elif report.drift.has_drift:
        lines.append("⚠️ **Schema drift detected since last scan:**")
        if report.drift.added_tools:
            lines.append(f"- Added tools: {', '.join(report.drift.added_tools)}")
        if report.drift.removed_tools:
            lines.append(f"- Removed tools: {', '.join(report.drift.removed_tools)}")
        if report.drift.changed_tools:
            lines.append(f"- Changed tools: {', '.join(report.drift.changed_tools)}")
    else:
        lines.append("No schema drift since last baseline.")
    lines.append("")

    lines.append("## Tool-by-tool breakdown")
    lines.append("")
    lines.append("| Tool | Score | Tier | Key findings |")
    lines.append("|---|---|---|---|")

    for tr in sorted(report.tool_reports, key=lambda t: -t.score):
        findings = []
        for f in tr.semantic.injection_findings:
            findings.append(f"`{f.pattern_label}`")
        for cat in tr.permissions.categories:
            findings.append(f"scope:{cat}")
        if tr.semantic.mismatch_flag:
            findings.append("name/desc mismatch")
        if tr.drift_flag:
            findings.append("DRIFTED")
        findings_str = ", ".join(findings) if findings else "—"
        lines.append(f"| `{tr.tool.name}` | {tr.score} | {_TIER_EMOJI[tr.tier]} {tr.tier} | {findings_str} |")

    lines.append("")
    lines.append("## Detail")
    for tr in sorted(report.tool_reports, key=lambda t: -t.score):
        if tr.score == 0:
            continue
        lines.append("")
        lines.append(f"### `{tr.tool.name}` — {tr.score}/100 ({tr.tier})")
        lines.append(f"> {tr.tool.description.strip()[:300]}")
        if tr.semantic.injection_findings:
            lines.append("")
            lines.append("**Injection-pattern findings:**")
            for f in tr.semantic.injection_findings:
                lines.append(f"- `{f.pattern_label}` (severity {f.severity}/10) — matched: \"{f.matched_snippet}\"")
        if tr.permissions.findings:
            lines.append("")
            lines.append("**Capability scope requested:**")
            seen = set()
            for f in tr.permissions.findings:
                if f.category in seen:
                    continue
                seen.add(f.category)
                lines.append(f"- `{f.category}` (weight {f.weight}) — inferred from {f.source}")
        if tr.semantic.mismatch_flag:
            lines.append("")
            lines.append(f"**Name/description semantic similarity:** {tr.semantic.name_desc_similarity:.2f} "
                         f"(low — description vocabulary doesn't track the tool's stated name)")
        if tr.drift_note:
            lines.append("")
            lines.append(f"**Drift:** {tr.drift_note}")

    lines.append("")
    lines.append("---")
    lines.append("_Generated by AgentWall-Supply v2.0 — AI Supply Chain & Tool-BOM Assurance Suite._")
    return "\n".join(lines)
